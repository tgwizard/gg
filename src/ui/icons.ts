export type IconName = keyof typeof ICONS;

/** Rows of pixels merged into one path per color: "M x y h n v 1 h -n z". */
export function iconPaths(rows: readonly string[]): { fill: string; d: string }[] {
  const byColor = new Map<string, string>();
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x]!;
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (ch !== "." && ch !== " ") {
        const fill = PALETTE[ch];
        if (!fill) throw new Error(`Unknown pixel color "${ch}"`);
        byColor.set(fill, `${byColor.get(fill) ?? ""}M${x} ${y}h${end - x}v1h${x - end}z`);
      }
      x = end;
    }
  });
  return [...byColor].map(([fill, d]) => ({ fill, d }));
}
